	self.cloneEntity[i]:cloneComponentOf(self.renderer)
	self.ctrans[i].parent = self.parentTrans
	self.parentTrans.children:pushBack(self.ctrans[i])
	self:addEffectLayers(i)
end

function TextAnim:getTextFontSize(comp)
    local text = self.text1
    -- local textColor = Amaz.Vector3f(1.0,1.0,1.0)
    local fontSize = 32
    if text then 
        
        if text.forceFlushCommandQueue then
            text:forceFlushCommandQueue()
        end
        local letters = text.letters
        if letters:size() > 0 then
            local letter0 = letters:get(0)
            fontSize = letter0 and letter0.letterStyle and letter0.letterStyle.fontSize
        end
    else
        fontSize = self.text.fontSize
    end
    return fontSize
end
local function random(x)
    return (math.sin(x * 392.0931) * 32917.0312) % 1
end
function TextAnim:seek(time)
    local w = Amaz.BuiltinObject:getInputTextureWidth()
    local h = Amaz.BuiltinObject:getInputTextureHeight()
    if self.first == true then
        self:initKeyFrame()
        --self:initAnimConfig()
        self.text.targetRTExtraSize = Amaz.Vector2f(0.0, 0)
	    self.text.renderToRT = true
        self.material[1] = self:setMatToSDFText(self.text, self.renderer)
        self.text:forceTypeSetting()
        local chars = self.text.chars
        self.ofs = Amaz.Vector2f(0.0)
        for i = 0, chars:size() - 1, 1 do
            local char = chars:get(i)
            if char.utf8code == "\n" then
                break
            end
            local x = char.initialPosition.x / w * 2.0
            local y = char.initialPosition.y / h * 2.0
            self.ofs = Amaz.Vector2f(x, y)
        end

        self.rowNum = 1
        local c = 0
        self.cNum = 0
        for i = 0, chars:size() - 1, 1 do
            local char = chars:get(i)
            if char.utf8code == "\n" then
                self.rowNum = self.rowNum + 1
                self.cNum = math.max(c, self.cNum)
                c = 1
            else
                c = c + 1
            end
        end

        self.cNum = math.max(c, self.cNum)

        if self.text.typeSettingKind == 1 then
            local t = self.cNum
            self.cNum = self.rowNum
            self.rowNum = t
        end
        -- for i = 1, 3 do
        --     self:addEntity(i)
        --     self.material[i + 1] = self:setMatToSDFText(self.cloneEntity[i]:getComponent("SDFText"), self.cloneEntity[i]:getComponent("MeshRenderer"))
        -- end
        
        self.CharForward = 0.85  --zi yu zi zhi jian de jian ge, fan wei shi [0, 1]
        self.CharDuration = 1.0 / (4 - self.CharForward * (4 - 1.0))
        self.CharForward = self.CharForward * self.CharDuration
        self.first = false
    else
    end


    if Amaz.Macros and Amaz.Macros.EditorSDK then
    else
        self.progress = time / self.duration % 1.0
    end
    
    self.material[1]:setFloat("u_RowNum", self.rowNum)
    self.material[1]:setFloat("u_cNum", self.cNum)
    self.material[1]:setFloat("u_Progress", self.progress)

    local size = self:getTextFontSize(self.text) / 32 * 720 / math.min(w, h)
    local displacement = self.Displacement:getCurPartVal(self.progress)
    local xpos = (self.PositionX:getCurPartVal(self.progress) - 8) / 400 * self.cNum * size
    local xScale = self.ScaleX:getCurPartVal(self.progress) * 0.01
    local yScale = self.ScaleY:getCurPartVal(self.progress) * 0.01
    local rotate = self.Rotate:getCurPartVal(self.progress)
    self.material[1]:setVec2("u_Ofs2", Amaz.Vector2f(xpos, 0.0))
    self.material[1]:setVec2("u_Scale2", Amaz.Vector2f(xScale, yScale))
    self.material[1]:setFloat("u_Angle2", rotate)

    self.material[1]:setFloat("u_Strength2", displacement * 0.003)
    local p = remap01(self.progress, 6 / 66, 10 / 66)
    local i = math.floor(p)
    p = remap01(p % 1.0, 0.2, 1.0)
    if i < 6 then 
        local perDisplacement = p * 2.9
        local perxpos =((p * 314 - 314) / 400 * self.cNum) * size - self.text.rect.width / w * 0.5
        local perxScale = p * 0.9 * (random(i) * 0.2 + 0.9)
        local peryScale = p * 0.9 * (random(-i - 100) * 0.2 + 0.9)
        local perrotate = p * 9 - 8
        self.material[1]:setVec2("u_Ofs1", Amaz.Vector2f(perxpos, 0.0))
        self.material[1]:setVec2("u_Scale1", Amaz.Vector2f(perxScale, peryScale))
        self.material[1]:setFloat("u_Angle1", perrotate)

        self.material[1]:setFloat("u_Strength1", perDisplacement * 0.003)
    else
        self.material[1]:setVec2("u_Ofs1", Amaz.Vector2f(-100, 0.0))
        self.material[1]:setVec2("u_Scale1", Amaz.Vector2f(0, 0))
    end


end


